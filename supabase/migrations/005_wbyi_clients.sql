create or replace function wbyi_admin_client_upsert(p_key text, p_email text, p_name text, p_company text, p_plan text, p_billing text)
returns uuid
language plpgsql security definer set search_path = public, extensions as $$
declare v_id uuid;
begin
  perform wbyi_check_key(p_key);
  insert into wbyi_clients (email, name, company, plan, billing)
  values (lower(btrim(p_email)), btrim(p_name), nullif(btrim(coalesce(p_company, '')), ''), coalesce(p_plan, 'starter'), coalesce(p_billing, 'stripe'))
  on conflict (email) do update set name = excluded.name, company = excluded.company, plan = excluded.plan, billing = excluded.billing
  returning id into v_id;
  return v_id;
end $$;

