create or replace function wbyi_admin_clients(p_key text)
returns json
language plpgsql security definer set search_path = public, extensions as $$
declare v json;
begin
  perform wbyi_check_key(p_key);
  select coalesce(json_agg(x order by x.created_at), '[]'::json) into v from (
    select c.id, c.email, c.name, c.company, c.plan, c.billing, c.anchor_day, c.created_at, c.last_login_at,
      coalesce((select json_agg(json_build_object('id', s.id, 'name', s.name, 'url', s.url, 'repo', s.repo, 'status', s.status))
                from wbyi_client_sites s where s.client_id = c.id), '[]'::json) as sites,
      (select count(*) from wbyi_requests q where q.client_id = c.id and q.status in ('new', 'in_progress', 'needs_info')) as open_requests
    from wbyi_clients c
  ) x;
  return v;
end $$;

-- Requests for the team queue, newest activity first, with the latest message.
create or replace function wbyi_admin_requests(p_key text, p_statuses text[])
returns json
language plpgsql security definer set search_path = public, extensions as $$
declare v json;
begin
  perform wbyi_check_key(p_key);
  select coalesce(json_agg(x order by x.priority_rank, x.updated_at desc), '[]'::json) into v from (
    select q.id, q.ref, q.title, q.details, q.status, q.size, q.created_at, q.updated_at, q.completed_at,
      c.id as client_id, c.name as client_name, c.email as client_email, c.plan,
      case c.plan when 'priority' then 0 when 'pro' then 1 when 'growth' then 2 else 3 end as priority_rank,
      s.name as site_name, s.url as site_url, s.repo as site_repo,
      (select count(*) from wbyi_attachments a where a.request_id = q.id) as attachments,
      (select json_build_object('author', m.author, 'body', left(m.body, 400), 'created_at', m.created_at)
         from wbyi_request_messages m where m.request_id = q.id order by m.created_at desc limit 1) as last_message
    from wbyi_requests q
    join wbyi_clients c on c.id = q.client_id
    left join wbyi_client_sites s on s.id = q.site_id
    where p_statuses is null or q.status = any (p_statuses)
    limit 300
  ) x;
  return v;
end $$;

create or replace function wbyi_admin_request_update(p_key text, p_request_id uuid, p_status text, p_size text)
returns void
language plpgsql security definer set search_path = public, extensions as $$
begin
  perform wbyi_check_key(p_key);
  if p_status is not null and p_status not in ('new', 'in_progress', 'needs_info', 'done', 'declined') then raise exception 'bad_status'; end if;
  if p_size is not null and p_size not in ('small', 'medium', 'large') then raise exception 'bad_size'; end if;
  update wbyi_requests
  set status = coalesce(p_status, status),
      size = coalesce(p_size, size),
      updated_at = now(),
      completed_at = case when p_status = 'done' then coalesce(completed_at, now())
                          when p_status is not null and p_status <> 'done' then null
                          else completed_at end
  where id = p_request_id;
end $$;

